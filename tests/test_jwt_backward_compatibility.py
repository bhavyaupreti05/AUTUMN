import pytest
from src.auth.security import verify_token
from src.config import settings
import jwt

# This token was generated BEFORE the library swap, using python-jose.
# Secret: "test_secret_123"
# Algorithm: "HS256"
# Payload: {"sub": "testuser", "exp": 4102444800}  # Year 2100
PRE_SWAP_JOSE_TOKEN = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiJ0ZXN0dXNlciIsImV4cCI6NDEwMjQ0NDgwMH0.-z2VHuLnmrE9rHWXcUQzzYg5zzW5zvzZDVltbj7oUqQ"

def test_preswap_token_verification(monkeypatch):
    """
    Validates that a JWT explicitly generated by the old python-jose library
    can be successfully verified by the new PyJWT implementation, ensuring
    mid-session users are not force-logged out.
    """
    # Temporarily force the settings to use the secret that signed the old token
    monkeypatch.setattr(settings, "JWT_SECRET", "test_secret_123")
    monkeypatch.setattr(settings, "JWT_ALGORITHM", "HS256")
    
    # Verify PyJWT decode doesn't fail on python-jose token
    decoded = verify_token(PRE_SWAP_JOSE_TOKEN)
    assert decoded == "testuser", "Token sub claim should match."

def test_pyjwt_exception_handling():
    """
    Validates that our codebase correctly catches PyJWT-specific exceptions 
    (DecodeError, InvalidSignatureError, ExpiredSignatureError) identically 
    to how it used to catch python-jose's JWTError.
    """
    # Verify our verify_token wrapper returns None instead of throwing 500s
    invalid_sig = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiJ0ZXN0dXNlciJ9.INVALID_SIGNATURE"
    
    # Triggers jwt.exceptions.InvalidSignatureError
    assert verify_token(invalid_sig) is None
    
    # Triggers jwt.exceptions.DecodeError
    assert verify_token("not.a.token") is None
